#!/usr/bin/env node
/**
 * blocks-showcase — generate a page that renders every installed block.
 *
 *   npm run blocks:showcase
 *
 * Writes:
 *   components/blocks/registry.generated.ts   name -> lazy import + export name
 *   app/blocks/page.tsx                       the scrollable showcase
 *
 * Two problems this has to solve honestly:
 *
 * 1. Export names vary. Some files default-export, some export one named
 *    component, some export several. The export is read out of the source
 *    rather than guessed, and files with no component export are skipped.
 *
 * 2. Most of these are COMPONENTS, not finished sections. Marquee needs
 *    children; a carousel needs slides. Rendering them bare will throw or draw
 *    nothing. So each block renders inside an error boundary: what works is
 *    shown, what throws degrades to a labelled card instead of taking the page
 *    down. That keeps the page truthful about what is actually usable.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, relative, basename, extname } from "node:path";
import { root } from "./lib/env.mjs";

const BLOCKS = join(root, "components", "blocks");
const MANIFEST = join(BLOCKS, "blocks.json");
const c = { dim: (s) => `\x1b[2m${s}\x1b[0m`, cyan: (s) => `\x1b[36m${s}\x1b[0m`, green: (s) => `\x1b[32m${s}\x1b[0m`, bold: (s) => `\x1b[1m${s}\x1b[0m` };

if (!existsSync(MANIFEST)) { console.error("no components/blocks/blocks.json — run `npm run blocks` first"); process.exit(1); }
const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));

/** Pick the component export from a source file. Returns {name, isDefault} or null. */
function pickExport(src, fileStem) {
  if (/export\s+default\s+(?:function|class|async\s+function)?/.test(src)) return { name: "default", isDefault: true };
  const named = [...src.matchAll(/export\s+(?:const|function|class)\s+([A-Z][A-Za-z0-9_]*)/g)].map((m) => m[1]);
  if (!named.length) return null;
  // Prefer the export whose name matches the file, else the first PascalCase one.
  const want = fileStem.replace(/[^a-z0-9]/gi, "").toLowerCase();
  const exact = named.find((n) => n.toLowerCase() === want);
  return { name: exact || named[0], isDefault: false };
}

const entries = [];
for (const b of manifest.blocks) {
  const file = (b.files || [])[0];
  if (!file) continue;
  const abs = join(root, file);
  if (!existsSync(abs)) continue;
  const src = readFileSync(abs, "utf8");
  const stem = basename(file, extname(file));
  const exp = pickExport(src, stem);
  if (!exp) continue;
  entries.push({
    id: `${b.registry}__${stem}`.replace(/[^A-Za-z0-9_]/g, "_"),
    name: b.title || b.name,
    slug: b.name,
    registry: b.registry,
    category: b.category,
    description: b.description || null,
    // import path relative to the generated file, which sits in components/blocks/
    importPath: "./" + relative(BLOCKS, abs).replace(/\\/g, "/").replace(/\.tsx?$/, ""),
    exportName: exp.name,
    isDefault: exp.isDefault,
    // "use client" blocks cannot be rendered from a server component tree directly
    client: /^\s*["']use client["']/m.test(src),
  });
}
entries.sort((a, b) => a.category.localeCompare(b.category) || a.registry.localeCompare(b.registry) || a.name.localeCompare(b.name));

/* ── registry.generated.ts ────────────────────────────────────────────────── */
const reg = `/**
 * GENERATED by scripts/blocks-showcase.mjs. Do not edit.
 *
 * Every installed block, lazily imported so the showcase code-splits instead of
 * shipping ${entries.length} components in one bundle.
 */
"use client";
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

export type BlockEntry = {
  id: string;
  name: string;
  slug: string;
  registry: string;
  category: string;
  description: string | null;
  Component: ComponentType<Record<string, unknown>>;
};

export const BLOCKS: BlockEntry[] = [
${entries.map((e) => `  {
    id: ${JSON.stringify(e.id)},
    name: ${JSON.stringify(e.name)},
    slug: ${JSON.stringify(e.slug)},
    registry: ${JSON.stringify(e.registry)},
    category: ${JSON.stringify(e.category)},
    description: ${JSON.stringify(e.description)},
    Component: dynamic(() => import(${JSON.stringify(e.importPath)}).then((m) => ({ default: (m as Record<string, unknown>)[${JSON.stringify(e.exportName)}] as ComponentType<Record<string, unknown>> })), { ssr: false, loading: () => null }),
  },`).join("\n")}
];

export const CATEGORIES = [...new Set(BLOCKS.map((b) => b.category))].sort();
export const REGISTRIES = [...new Set(BLOCKS.map((b) => b.registry))].sort();
`;
writeFileSync(join(BLOCKS, "registry.generated.ts"), reg);

/* ── the showcase page ────────────────────────────────────────────────────── */
mkdirSync(join(root, "app", "blocks"), { recursive: true });
writeFileSync(join(root, "app", "blocks", "page.tsx"), `import type { Metadata } from "next";
import { BlocksShowcase } from "@/components/blocks-showcase";

export const metadata: Metadata = {
  title: "Block library",
  description: "Every installed block, rendered so you can judge it before using it.",
};

export default function BlocksPage() {
  return <BlocksShowcase />;
}
`);

console.log(`\n${c.bold("blocks-showcase")}\n`);
const byCat = {};
for (const e of entries) byCat[e.category] = (byCat[e.category] || 0) + 1;
console.log(`  ${c.dim("renderable")} ${c.cyan(String(entries.length))} of ${manifest.blocks.length} manifest entries`);
console.log(`  ${c.dim("skipped")}    ${manifest.blocks.length - entries.length} with no detectable component export`);
console.log(`  ${c.dim("categories")} ${Object.entries(byCat).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k}:${v}`).join("  ")}`);
console.log(`\n  ${c.green("wrote")} components/blocks/registry.generated.ts`);
console.log(`  ${c.green("wrote")} app/blocks/page.tsx  ${c.dim("-> http://localhost:3000/blocks")}\n`);
